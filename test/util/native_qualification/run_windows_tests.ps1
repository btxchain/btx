# Run in a Visual Studio Developer PowerShell on Windows 10/11. This launches
# a real AppContainer and an owned loopback listener; it sends no Internet data.
[CmdletBinding()]
param(
    [Parameter(Mandatory=$true)][string]$QualifierPath,
    [string]$ProbePath,
    [string]$ReportPath = "native-windows-results.json"
)
$ErrorActionPreference = "Stop"
$qualifier = (Resolve-Path -LiteralPath $QualifierPath).Path
$root = Join-Path ([IO.Path]::GetTempPath()) ("btx-native-test-" + [guid]::NewGuid().ToString("N"))
[IO.Directory]::CreateDirectory($root) | Out-Null
$package = Join-Path $root "package"
[IO.Directory]::CreateDirectory($package) | Out-Null
$listener = [Net.Sockets.TcpListener]::new([Net.IPAddress]::Loopback, 0)
$oldSentinel = [Environment]::GetEnvironmentVariable("BTX_NATIVE_SECRET_SENTINEL", "Process")
$utf8 = [Text.UTF8Encoding]::new($false)
function Digest([byte[]]$Bytes) {
    $hasher = [Security.Cryptography.SHA384]::Create()
    try { return ([BitConverter]::ToString($hasher.ComputeHash($Bytes))).Replace("-", "").ToLowerInvariant() }
    finally { $hasher.Dispose() }
}
function FileEntry([string]$Name) {
    $file = Join-Path $package $Name
    return @{ path=$Name; sha384=(Get-FileHash -LiteralPath $file -Algorithm SHA384).Hash.ToLowerInvariant(); bytes=(Get-Item -LiteralPath $file).Length }
}
try {
    if (!$ProbePath) {
        $ProbePath = Join-Path $root "sandbox-probe.exe"
        $source = Join-Path $PSScriptRoot "windows_sandbox_probe.cpp"
        Push-Location $root
        try {
            & cl.exe /nologo /std:c++20 /W4 /EHsc $source "/Fe$ProbePath" ws2_32.lib
            if ($LASTEXITCODE -ne 0) { throw "Native Windows probe compilation failed" }
        } finally { Pop-Location }
    }
    Copy-Item -LiteralPath (Resolve-Path -LiteralPath $ProbePath).Path -Destination (Join-Path $package "probe.exe")
    $witness = Join-Path $root "private-witness.txt"
    [IO.File]::WriteAllText($witness, "outside-private-tree", $utf8)
    $listener.Start()
    $port = $listener.LocalEndpoint.Port
    [IO.File]::WriteAllText((Join-Path $package "probe-config.txt"), "$witness`n$port`n", $utf8)
    $expected = $utf8.GetBytes("filesystem-denied network-denied environment-clean native-executed`n")
    $request = @{ probe=@{
        root=$package; executable="probe.exe"; files=@((FileEntry "probe.exe"), (FileEntry "probe-config.txt"));
        output_relative_path="probe-result.txt"; expected_output_sha384=(Digest $expected);
        expected_output_bytes=$expected.Length; max_package_bytes=16777216; wall_seconds=15
    }}
    $requestFile = Join-Path $root "request.json"
    [IO.File]::WriteAllText($requestFile, ($request | ConvertTo-Json -Depth 12 -Compress), $utf8)
    [Environment]::SetEnvironmentVariable("BTX_NATIVE_SECRET_SENTINEL", "must-not-reach-child", "Process")
    $raw = & $qualifier tool $requestFile
    $exit = $LASTEXITCODE
    $result = $raw | ConvertFrom-Json
    if ($exit -ne 0 -or !$result.success -or !$result.module_passed) { throw "Native AppContainer probe failed: $raw" }
    if ($result.btx_deployment_qualified) { throw "Component probe illegally qualified the deployment" }
    $output = [IO.File]::ReadAllBytes((Join-Path $package "probe-result.txt"))
    if ((Digest $output) -ne (Digest $expected)) { throw "Native output digest mismatch" }
    $replayRaw = & $qualifier tool $requestFile
    $replayExit = $LASTEXITCODE
    $replay = $replayRaw | ConvertFrom-Json
    if ($replayExit -ne 2 -or $replay.error -ne "NATIVE_TOOL_STALE_OUTPUT") { throw "Preexisting output was accepted" }
    $report = @{
        schema="BTX/NativeWindowsPlatformTest/v1"; native_appcontainer="PASS"; native_escape_probe="PASS";
        stale_output_rejected="PASS"; native_result=$result; btx_deployment_qualified=$false;
        automatic_spend_atoms="0"; observed_os=[Environment]::OSVersion.VersionString;
        created_at_ms=[DateTimeOffset]::UtcNow.ToUnixTimeMilliseconds()
    }
    [IO.File]::WriteAllText([IO.Path]::GetFullPath($ReportPath), ($report | ConvertTo-Json -Depth 20), $utf8)
    $report | ConvertTo-Json -Depth 20
} finally {
    $listener.Stop()
    [Environment]::SetEnvironmentVariable("BTX_NATIVE_SECRET_SENTINEL", $oldSentinel, "Process")
    # This directory was freshly generated by this exact test invocation.
    if (Test-Path -LiteralPath $root) { Remove-Item -LiteralPath $root -Recurse -Force }
}
